const STORAGE_KEY = '@user_language';

interface LanguageContextType {
  currentLanguage: LanguageCode;
  setLanguage: (lang: LanguageCode) => Promise<void>;
  chatLanguage: LanguageCode;
  setChatLanguage: (lang: LanguageCode) => Promise<void>;
  t: (key: string) => string;
  getGreeting: (name?: string | null) => string;
  languages: LanguageOption[];
}

const LanguageContext = createContext<LanguageContextType>({
  currentLanguage: 'en',
  setLanguage: async () => {},
  chatLanguage: 'en',
  setChatLanguage: async () => {},
  t: (key: string) => key,
  getGreeting: (name?: string | null) => name ? `Hello, ${name}!` : 'Hello!',
  languages: SUPPORTED_LANGUAGES,
});

export const LanguageProvider: React.FC<{children: ReactNode}> = ({children}) => {
  const [currentLanguage, setCurrentLanguageState] = useState<LanguageCode>('en');
  const [chatLanguage, setChatLanguageState] = useState<LanguageCode>('en');

  useEffect(() => {
    (async () => {
      try {
        const savedLang = await AsyncStorage.getItem(STORAGE_KEY);
        if (savedLang === 'en' || savedLang === 'hi' || savedLang === 'mr') {
          setCurrentLanguageState(savedLang);
        }
        const savedChatLang = await AsyncStorage.getItem('@sahayak_chat_language');
        if (savedChatLang === 'en' || savedChatLang === 'hi' || savedChatLang === 'mr') {
          setChatLanguageState(savedChatLang);
        } else if (savedLang === 'en' || savedLang === 'hi' || savedLang === 'mr') {
          setChatLanguageState(savedLang);
        }
      } catch (e) {
        // Fallback to English
      }
    })();
  }, []);

  const setLanguage = async (lang: LanguageCode) => {
    try {
      await AsyncStorage.setItem(STORAGE_KEY, lang);
      setCurrentLanguageState(lang);
    } catch (e) {
      console.error('Failed to save language', e);
    }
  };

  const setChatLanguage = async (lang: LanguageCode) => {
    try {
      await AsyncStorage.setItem('@sahayak_chat_language', lang);
      setChatLanguageState(lang);
    } catch (e) {
      console.error('Failed to save AI chat language', e);
    }
  };

  const getGreeting = (name?: string | null): string => {
    const trimmed = name?.trim();
    if (!trimmed) {
      if (currentLanguage === 'hi') return 'नमस्ते!';
      if (currentLanguage === 'mr') return 'नमस्कार!';
      return 'Hello!';
    }
    if (currentLanguage === 'hi') return `नमस्ते, ${trimmed}!`;
    if (currentLanguage === 'mr') return `नमस्कार, ${trimmed}!`;
    return `Hello, ${trimmed}!`;
  };

  const t = (key: string): string => {
    const langDict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
    if (langDict[key]) {
      return langDict[key];
    }
    // Fallback to English if translation is missing in the chosen language
    if (TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return key;
  };

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage,
        chatLanguage,
        setChatLanguage,
        t,
        getGreeting,
        languages: SUPPORTED_LANGUAGES,
      }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
export default LanguageContext;
